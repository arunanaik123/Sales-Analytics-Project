/*
============================================================
PROJECT : Sales Analytics
MODULE  : Executive Dashboard
DESCRIPTION:
This module analyzes the overall sales performance of the
company by evaluating key executive-level business KPIs.
============================================================
*/


/*
============================================================
KPI 1 : Total Revenue

Business Objective:
Measure the total revenue generated by the company during
the analysis period to evaluate overall business performance.
============================================================
*/

SELECT
    ROUND(SUM(sales),2) AS total_revenue
FROM Order_Details;



/*
============================================================
KPI 2 : Total Orders

Business Objective:
Determine the total number of customer orders placed to
measure overall sales activity.
============================================================
*/

SELECT
    COUNT(*) AS total_orders
FROM Orders;



/*
============================================================
KPI 3 : Active Customers

Business Objective:
Identify the number of unique customers who placed at least
one order during the analysis period.
============================================================
*/

SELECT
    COUNT(DISTINCT customer_id) AS total_customers
FROM Orders;



/*
============================================================
KPI 4 : Average Order Value (AOV)

Business Objective:
Calculate the average revenue generated per order to
understand customer purchasing behavior.
============================================================
*/

SELECT

    ROUND(
        SUM(sales) /
        COUNT(DISTINCT order_number),
    2) AS average_order_value

FROM Order_Details;



/*
============================================================
KPI 5 : Annual Revenue Performance

Business Objective:
Identify the highest revenue generating year to evaluate
business growth over time.
============================================================
*/

SELECT

    YEAR(o.order_date) AS sales_year,

    ROUND(
        SUM(od.sales),
    2) AS total_revenue

FROM Orders o

JOIN Order_Details od
ON o.order_number = od.order_number

GROUP BY YEAR(o.order_date)

ORDER BY total_revenue DESC;



/*
============================================================
KPI 6 : Quarterly Revenue Performance

Business Objective:
Analyze quarterly sales performance to identify seasonal
revenue patterns throughout the year.
============================================================
*/

SELECT

    YEAR(o.order_date) AS sales_year,

    QUARTER(o.order_date) AS sales_quarter,

    ROUND(
        SUM(od.sales),
    2) AS total_revenue

FROM Orders o

JOIN Order_Details od
ON o.order_number = od.order_number

GROUP BY

    YEAR(o.order_date),

    QUARTER(o.order_date)

ORDER BY

    sales_year,

    total_revenue DESC;



/*
============================================================
KPI 7 : Monthly Revenue Performance

Business Objective:
Determine the highest revenue generating month each year
to identify seasonal demand patterns.
============================================================
*/

SELECT

    YEAR(o.order_date) AS sales_year,

    MONTH(o.order_date) AS sales_month,

    MONTHNAME(o.order_date) AS month_name,

    ROUND(
        SUM(od.sales),
    2) AS total_revenue

