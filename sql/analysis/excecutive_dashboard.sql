JOIN Order_Details od
ON o.order_number = od.order_number

GROUP BY

    YEAR(o.order_date),

    MONTH(o.order_date),

    MONTHNAME(o.order_date)

ORDER BY

    sales_year,

    total_revenue DESC;



/*
============================================================
KPI 8 : Monthly Revenue Trend

