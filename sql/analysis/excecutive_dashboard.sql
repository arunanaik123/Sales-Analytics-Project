/*
============================================================
KPI 9 : Month-over-Month Sales Growth

Business Objective:
Measure monthly sales growth by comparing each month's
revenue with the previous month to identify business
growth and decline trends.
============================================================
*/

WITH MonthlyRevenue AS
(
    SELECT

        YEAR(o.order_date) AS sales_year,

        MONTH(o.order_date) AS sales_month,

        MONTHNAME(o.order_date) AS month_name,

        SUM(od.sales) AS total_revenue

    FROM Orders o

    JOIN Order_Details od
    ON o.order_number = od.order_number

    GROUP BY

        YEAR(o.order_date),

        MONTH(o.order_date),

        MONTHNAME(o.order_date)
),

RevenueComparison AS
(
    SELECT

        sales_year,

        sales_month,

        month_name,

        ROUND(total_revenue,2) AS current_month_revenue,

        LAG(total_revenue)
        OVER(
            ORDER BY sales_year,sales_month
        ) AS previous_month_revenue

    FROM MonthlyRevenue
)

SELECT

    sales_year,

    month_name,

    current_month_revenue,

    ROUND(previous_month_revenue,2) AS previous_month_revenue,

    ROUND(
        (
            current_month_revenue -
            previous_month_revenue
        )
        /
        NULLIF(previous_month_revenue,0)
        *100,
    2) AS growth_percentage,

    CASE

        WHEN previous_month_revenue IS NULL
            THEN 'N/A'

        WHEN current_month_revenue > previous_month_revenue
            THEN 'Growing'

        WHEN current_month_revenue < previous_month_revenue
            THEN 'Declining'

        ELSE 'Stable'

    END AS trend

FROM RevenueComparison;



/*
============================================================
KPI 10 : Revenue Contribution by Country

Business Objective:
Identify the countries generating the highest revenue to
understand the company's strongest geographical markets.
============================================================
*/

SELECT

    c.country,

    ROUND(
        SUM(od.sales),
    2) AS total_revenue

FROM Orders o

JOIN Order_Details od
ON o.order_number = od.order_number

JOIN Customers c
ON o.customer_id = c.customer_id

GROUP BY
    c.country

ORDER BY
    total_revenue DESC;